"""Exact integer port of the ArtPoW difficulty rule (src/Exp2.sol and _scheduleTarget).

Kept bit-for-bit identical to the contract: test/Differential.t.sol checks vectors generated by this module.
"""

SUPPLY_PER_MONTH = 1000
CLAIMS_PER_DOUBLING = 10
FLOOR_DIFFICULTY_BITS = 28
MAX_TARGET = 1 << (256 - FLOOR_DIFFICULTY_BITS)


def _trunc_divmod(num: int, den: int) -> tuple[int, int]:
    """Solidity signed division: quotient truncated toward zero, remainder has the sign of `num`."""
    q = abs(num) // den
    q = q if num >= 0 else -q
    return q, num - q * den


def mul_exp2(x: int, num: int, den: int, cap: int) -> int:
    q, r = _trunc_divmod(num, den)
    if r < 0:
        q -= 1
        r += den
    frac = (r << 16) // den
    factor = 65536 + ((195766423245049 * frac + 971821376 * frac**2 + 5127 * frac**3 + (1 << 47)) >> 48)
    y = x * factor // 65536
    if q >= 0:
        if q >= 256 or y > (cap >> q):
            return cap
        y <<= q
    else:
        y = 0 if -q >= 256 else y >> -q
    if y > cap:
        return cap
    return 1 if y == 0 else y


def schedule_target(duration: int, elapsed: int, minted: int, max_target: int = MAX_TARGET) -> int:
    ahead = elapsed * SUPPLY_PER_MONTH - minted * duration
    return mul_exp2(max_target, ahead, duration * CLAIMS_PER_DOUBLING, max_target)
